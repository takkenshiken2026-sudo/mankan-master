def load_freq() -> dict[str, int]:
    out: dict[str, int] = {}
    if not CANDIDATES_TSV.exists():
        return out
    with CANDIDATES_TSV.open() as f:
        next(f)  # ヘッダ
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) != 2:
                continue
            freq, term = parts
            try:
                out[term] = int(freq)
            except ValueError:
                continue
    return out


def fuzzy_freq(term: str, freq_map: dict[str, int]) -> int:
    # 完全一致
    if term in freq_map:
        return freq_map[term]
    # 部分一致のうち最大
    candidates = [v for k, v in freq_map.items() if term in k or k in term]
    return max(candidates, default=0)


def main() -> int:
    freq_map = load_freq()
    rows: list[dict[str, object]] = []
    seen_terms: set[str] = set()
    for idx, (cat, tag, tier, term, note) in enumerate(ENTRIES, start=1):
        key = re.sub(r"\s+", "", term)
        if key in seen_terms:
            print(f"WARN: duplicate term: {term}")
            continue
        seen_terms.add(key)
        rows.append({
            "order": idx,
            "category": cat,
            "tag": tag,
            "tier": tier,
            "term": term,
            "freq": fuzzy_freq(term, freq_map),
            "note": note,
        })

    out_path = ROOT / "data" / "glossary_headlist_draft.csv"
    with out_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["order", "category", "tag", "tier", "term", "freq", "note"])
        writer.writeheader()
        writer.writerows(rows)

    # サマリ
    from collections import Counter
    print(f"total terms: {len(rows)}")
    print()
    print("category x tier:")
    cat_tier = Counter((r["category"], r["tier"]) for r in rows)
    for cat in ("法令・制度", "契約・実務", "設備・その他"):
        a = cat_tier.get((cat, "A"), 0)
        b = cat_tier.get((cat, "B"), 0)
        c = cat_tier.get((cat, "C"), 0)
        print(f"  {cat:10s}  A:{a:3d}  B:{b:3d}  C:{c:3d}  small total:{a+b+c:3d}")
    print()
    print("tag breakdown:")
    tag_counter = Counter(r["tag"] for r in rows)
    for tag, n in tag_counter.most_common():
        print(f"  {n:3d}  {tag}")
    print()
    print(f"wrote: {out_path}")
    return 0


