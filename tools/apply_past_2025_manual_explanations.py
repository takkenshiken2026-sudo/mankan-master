def main() -> int:
    with DATA_CSV.open(encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        fieldnames = reader.fieldnames or []
        rows = list(reader)

    updated = 0
    for qno, explanation in sorted(MANUAL_2025.items()):
        row = next(
            (r for r in rows if r["exam_year"] == "2025" and int(r["question_no"]) == qno),
            None,
        )
        if not row:
            print(f"WARN: missing row 2025-{qno:02d}", file=sys.stderr)
            continue
        row["explanation"] = explanation.strip()
        row["explanation_summary"] = ""
        row["explanation_correct"] = ""
        row["explanation_choices"] = ""
        row["explanation_point"] = ""
        updated += 1
        print(f"manual Q{qno:02d}")

    with DATA_CSV.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    print(f"Applied {updated} manual explanation(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
